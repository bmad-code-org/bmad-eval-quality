/** the only artifact that reaches the executing caller. */
import { z } from 'zod'
import { Behavior, Budgets, ScopedResource } from './eval-contract.ts'
import { InterfaceKind } from './interface.ts'
import { lineageFields } from './lineage.ts'
import { Digest, Identifier, OracleId } from './primitives.ts'

/**
 * AD-3's generated evaluator-facing direction, keyed by the oracle it belongs
 * to. The evaluator sees oracle identifiers but never step identifiers: AD-23
 * requires every finding to cite its oracle, and AD-16 specifically bars step
 * identifiers from reaching it.
 *
 * No `behaviorId`: `Behavior.oracles` is an array, so two behaviours can cite
 * one oracle and a single behaviour id on a direction would not be truthful.
 */
export const BriefDirection = z.strictObject({
	oracleId: OracleId,
	text: z
		.string()
		.min(1)
		.describe(
			'The generated prose. `seal` renders each evidence target as a descriptive reference derived from the step\'s operation and selection predicate, such as "the response you obtained when you sent an invalid identifier", never as the step identifier itself; the mapping from step to phrase is one-way. It never carries a prescribed action sequence.',
		),
})

export type BriefDirection = z.infer<typeof BriefDirection>

/**
 * Interface identity only, no operation inventory: shipping one would hand the
 * evaluator the action list AD-39 keeps from it, one artifact over from where
 * AD-5's scripting-shape predicate looks. Withholding it costs nothing in
 * practice: the isolation manifest records an arm finding a search parameter
 * by trying `?search=`, `?query=`, and `?q=` in turn, and that arm still
 * caught the defect.
 */
export const BriefInterface = z.strictObject({
	logicalId: Identifier.describe(
		'AD-35 binds the brief as it binds the contract: a logical interface identifier only, never a URL, host, or port. The brief is the artifact that actually reaches the executing caller, so a URL leaking onto it defeats the mapping AD-35 keeps outside the package.',
	),
	kind: InterfaceKind,
})

export const SealedEvaluatorBrief = z
	.strictObject({
		...lineageFields,
		contractDigest: Digest.describe(
			'Binds this brief to the contract it seals. The brief carries no contract identifier of its own and no identity field at all: every artifact that refers to a brief does so by `sealedBriefDigest`, so an identifier would be a second name nothing reads.',
		),
		behaviors: z
			.array(Behavior)
			.min(1)
			.describe(
				"The contract's behaviours, carried through unchanged. At least one, on the contract's own reasoning: a brief with no behaviour directs nothing.",
			),
		directions: z
			.array(BriefDirection)
			.min(1)
			.describe(
				"AD-3's generated evaluator-facing directions, one per discharged oracle. At least one, on the same reasoning as `behaviors` above: a brief with no direction verifies nothing.",
			),
		permittedInterfaces: z.array(BriefInterface),
		scopedResources: z
			.array(ScopedResource)
			.describe(
				"AD-16's scoped resource references. Not nullable here, unlike on the contract: absent-versus-explicitly-empty is an AD-31 grading of a CALLER declaration, and this artifact is generated by `seal`, which always knows the answer. No scoped reference may resolve to a forbidden input; that resolution is `scoped-reference-resolves-forbidden` at compile time and is not a schema check.",
			),
		budgets: Budgets.describe(
			"The contract's declared ceilings, carried because AD-16 says the caller who executes needs the ceilings the isolation manifest reports against. The manifest's own `resourceCeilings` is a different shape and a different concern: this is a declaration, that is a record of what the harness enforced.",
		),
		safetyLimits: z.array(z.string()),
		probeStepBound: z
			.int()
			.min(0)
			.nullable()
			.describe(
				"AD-16's declared bound on enumerated probe steps, carried through from the contract. The brief-side scripting audit reads it after generation; that audit and its AD-5 code are Epic 2's.",
			),
	})
	.meta({
		id: 'SealedEvaluatorBrief',
		description:
			"The sealed evaluator brief, with no prior art. AD-16 fixes what it carries: the contract's behaviours, the generated evaluator-facing directions of AD-3, permitted interfaces, and scoped resource references, plus budgets and safety limits. It also fixes what the brief never carries: author commentary, the interaction plan, or the plan's step identifiers, and never a prescribed action sequence. Those exclusions are structural rather than conventional: this object is strict, so a brief carrying `interactionPlan`, `commentary`, or a `stepId` fails with `unrecognized_keys`, and the story asserts each one as a reject fixture rather than assuming it from strictness. It carries no identity field of its own, because every artifact that refers to it does so by digest.",
	})

export type SealedEvaluatorBrief = z.infer<typeof SealedEvaluatorBrief>
