// The registry over every committed tutorial chain, and the one module that
// knows how many there are. The generator and the drift check both import
// `buildTutorials`, so neither can address a file the other does not, and a
// chain added under `scripts/tutorials/` reaches both by being listed here.
//
// A tutorial chain exists so a documentation page can be executed rather than
// read. Every file it emits is an input some command on that page names, and
// every digest inside it is computed from bytes this repository ships. The
// committed worked examples under `_bmad-output/` make the weaker claim: they
// are generated by the shipped functions and they cannot be re-run from the
// command line, because their records point at private references whose
// declared digests no file produces.
//
// Run by `node` directly: type stripping erases types only, so no TypeScript
// enum, namespace, parameter property, or non-type re-export may appear in this
// file or anything it imports.
import { AGENT_LABEL, buildAgentTutorial } from './tutorials/agent.ts'
import { buildSkillTutorial, SKILL_LABEL } from './tutorials/skill.ts'
import { buildToolUseTutorial, TOOL_USE_LABEL } from './tutorials/tool-use.ts'
import {
	buildWalkthroughTutorial,
	WALKTHROUGH_LABEL,
} from './tutorials/walkthrough.ts'
import {
	buildWorkflowTutorial,
	WORKFLOW_TUTORIAL_LABEL,
} from './tutorials/workflow.ts'
import { fail } from './worked-example-shared.ts'

/** Every chain's builder, in the order a reader meets them in the docs. */
const BUILDERS = [
	buildWalkthroughTutorial,
	buildAgentTutorial,
	buildSkillTutorial,
	buildWorkflowTutorial,
	buildToolUseTutorial,
]

/** The directories the emitted keys live under, for the generator's report. */
export const TUTORIAL_LABELS = [
	WALKTHROUGH_LABEL,
	AGENT_LABEL,
	SKILL_LABEL,
	WORKFLOW_TUTORIAL_LABEL,
	TOOL_USE_LABEL,
]

export function buildTutorials(): Map<string, string> {
	const files = new Map<string, string>()
	for (const build of BUILDERS) {
		for (const [path, text] of build()) {
			// Two chains claiming one path would make the later build win silently,
			// and the drift check would then report a pass over the loser.
			if (files.has(path)) fail(`${path}: two chains emit this path`)
			files.set(path, text)
		}
	}
	return files
}

/**
 * Hand-authored program source a chain ships and a builder reads.
 *
 * Everything else under `examples/tutorials/` is emitted, and the drift check
 * sweeps for files no builder emits, because a reader who opens one is reading
 * bytes nothing holds. These are the exception, and they have to be: the
 * tool-use builder imports `notes-store.mjs` so the committed observations and a
 * reader's own run of the server come from one definition of what the tools
 * answer. A builder that emitted its own input would be comparing a file
 * against itself, which is the vacuous pass the sweep exists to prevent.
 *
 * The sweep still requires each of these to exist, so a deleted fixture fails
 * here rather than at the moment a reader runs the page.
 */
export const TUTORIAL_SOURCES = [
	'examples/tutorials/tool-use/notes-store.mjs',
	'examples/tutorials/tool-use/run-tool-calls.mjs',
	'examples/tutorials/tool-use/tool-server.mjs',
]

/** Every file the tutorials own, which is what the drift check compares. */
export const TUTORIAL_FILES = [...buildTutorials().keys()].sort()
